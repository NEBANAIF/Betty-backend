package com.company.erp.purchase;

import com.company.erp.common.audit.BaseEntity;
import com.company.erp.user.User;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.BatchSize;

import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/**
 * One confirmed delivery into the warehouse: who counted what, when. A purchase can be received in several
 * deliveries (partial deliveries); each one is a receipt. {@code requestId} is generated by the screen when it
 * opens and is unique, so pressing "Confirm" twice (or a retry after a slow network) can never add the stock twice.
 */
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "purchase_receipts")
public class PurchaseReceipt extends BaseEntity {

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "purchase_order_id", nullable = false)
    private PurchaseOrder purchaseOrder;

    @Column(name = "request_id", unique = true)
    private UUID requestId;

    @Column(name = "received_date", nullable = false)
    private LocalDate receivedDate;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "received_by", nullable = false)
    private User receivedBy;

    @Column(length = 300)
    private String note;

    @OneToMany(mappedBy = "receipt", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("id ASC")
    @BatchSize(size = 50)
    private List<PurchaseReceiptLine> lines = new ArrayList<>();

    public void addLine(PurchaseReceiptLine line) {
        line.setReceipt(this);
        lines.add(line);
    }
}
